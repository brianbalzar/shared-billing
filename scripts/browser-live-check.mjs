import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
const errors = []; page.on('pageerror', e => errors.push(e.message));
const response = await page.goto(process.argv[2] || 'https://brianbalzar.github.io/shared-billing/');
if (!response?.ok()) throw new Error(`Site returned ${response?.status()}`);
await page.waitForFunction(() => !document.querySelector('.example-card button')?.disabled, null, { timeout: 60000 });
if (await page.locator('.chosen').count()) throw new Error('Landing recommendations should not be selected automatically');
const recommendation = await page.locator('.example-copy strong').innerText();
await page.screenshot({ path: 'qa/live-landing.png' });
await page.getByRole('button', { name: 'Try it', exact: true }).click();
await page.waitForFunction(() => document.querySelectorAll('.chosen').length === 2);
const names = await page.locator('.chosen .node-name').allTextContents();
if (new Set(names).size !== 2 || names.join(' + ') !== recommendation) throw new Error('Try it must load the recommended actors');
await page.waitForFunction(() => document.querySelector('.link-hit') || document.querySelector('.no-connection'));
await page.screenshot({ path: 'qa/live.png' });
if (errors.length) throw new Error(errors.join('\n'));
console.log('Landing page, random recommendations, and opt-in graph loading verified:', recommendation);
await browser.close();
