import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
await page.goto('http://127.0.0.1:5173/shared-billing/');
await page.waitForFunction(() => !document.querySelector('.example-card button')?.disabled);
async function add(name) { const search = page.getByRole('combobox'); await search.fill(name); await page.getByRole('option').filter({ hasText: name }).first().waitFor(); await search.press('Enter'); }
await add('Setsuko Hara'); await add('Ziggy Marley');
await page.getByRole('heading', { name: 'No connection at this depth.' }).waitFor();
await page.locator('#people-between').fill('3');
await page.getByRole('button', { name: /Route 1 of 7/ }).waitFor();
await page.screenshot({ path: 'qa/deep.png' });
await page.getByRole('button', { name: 'Next route for Setsuko Hara and Ziggy Marley' }).click();
await page.getByRole('button', { name: /Route 2 of 7/ }).waitFor();
await page.getByRole('heading', { name: 'Setsuko Hara and Ziggy Marley' }).waitFor();
await page.keyboard.press('Escape');
await page.reload();
await page.waitForFunction(() => !document.querySelector('.example-card button')?.disabled);
await page.getByRole('button', { name: 'Try it', exact: true }).click();
await page.getByRole('button', { name: 'John Goodman, show linking films. Drag to pin.', exact: true }).waitFor();
await add('Billy Crystal'); await add('Kevin Bacon');
await page.locator('.hub .node-button').first().waitFor();
await page.screenshot({ path: 'qa/hub.png' });
await add('Meg Ryan'); await add('Julia Roberts');
if (!(await page.getByRole('combobox').isDisabled())) throw new Error('Six-actor maximum not enforced');
await page.getByRole('button', { name: 'Popular films', exact: true }).click();
await page.getByRole('radio', { name: /Hit films/ }).click();
await page.waitForFunction(() => document.querySelector('.summary')?.textContent?.includes('shared'));
await page.screenshot({ path: 'qa/six.png' });
console.log('Deeper-route navigation, no-connection state, hubs, filters, and the six-actor maximum passed.');
await browser.close();
